// "zh-TW", "zh-HK", "zh-Hant-..." -> zh-Hant; other Chinese -> zh-Hans.
export function langFromLocale(locale: string): Lang {
  const l = (locale || '').toLowerCase();
  if (/^zh\b/.test(l)) return /hant|-tw|-hk|-mo/.test(l) ? 'zh-Hant' : 'zh-Hans';
  if (/^yue\b/.test(l)) return 'zh-Hant';
  if (/^es\b/.test(l)) return 'es';
  return 'en';
}
const isLang = (v: unknown): v is Lang => v === 'en' || v === 'es' || v === 'zh-Hans' || v === 'zh-Hant';

export function initialLang(): Lang {
  try {
    const saved = window.localStorage.getItem('primacura-lang');
    if (isLang(saved)) return saved;
  } catch { /* storage blocked: use the browser language */ }
  return typeof navigator !== 'undefined' ? langFromLocale(navigator.language) : 'en';
}

export function saveLang(lang: Lang) {
  try { window.localStorage.setItem('primacura-lang', lang); } catch { /* not saved: fine */ }
}

export const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: 'en',
  setLang: () => undefined,
});

export type I18n = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: StringKey, vars?: Record<string, string | number>) => string;
  conditions: Condition[];
  howTos: HowTo[];
  diagrams: Record<string, Diagram>;
  ageLabels: string[];
  ageHints: string[];
  cardAge: (age: string) => string;
};

export function i18nFor(lang: Lang, setLang: (lang: Lang) => void = () => undefined): I18n {
  const strings = STRINGS[lang];
  return {
    lang,
    setLang,
    t: (key, vars) => strings[key].replace(/\{(\w+)\}/g, (m, v: string) => (vars && v in vars ? String(vars[v]) : m)),
    conditions: DATA[lang].conditions,
    howTos: DATA[lang].howTos,
    // Diagrams without a translated version fall back to English.
    diagrams: { ...diagrams, ...DATA[lang].diagrams },
    ageLabels: AGE_LABELS[lang],
    ageHints: AGE_HINTS[lang],
    cardAge: (age) => CARD_AGE[lang]?.[age] ?? age,
  };
}

export function useI18n(): I18n {
  const { lang, setLang } = useContext(LangContext);
  return i18nFor(lang, setLang);
}
